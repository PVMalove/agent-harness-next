#!/usr/bin/env python3
"""Build-time инструмент каталога FMEA (ADR 0041).

`generate` пишет `harness/fmea/ids.py` с `FmeaId` из `harness/fmea/catalog.toml`;
`generate --check` только сравнивает модуль с каталогом и завершается с кодом 1 при расхождении;
`new <title>` дописывает заготовку записи с новым uuid4 и перегенерирует модуль. `id` никогда
не вводится вручную: у CLI нет такой опции. `db` собирает из каталога SQLite-файл
`.harness/fmea.db` только для запросов `harness fmea show`; файл не коммитится.
"""

from __future__ import annotations

import argparse
import sys
import uuid
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from harness.errors import print_and_exit
from harness.fmea.catalog import (
    CATALOG_PATH,
    FmeaCatalogError,
    FmeaEntry,
    FIELDS,
    load_catalog,
    member_name,
    parse_catalog,
)
from harness.fmea.db import DB_PATH, FmeaDbError, build_db

MODULE_PATH = CATALOG_PATH.with_name("ids.py")
REGENERATE = "python scripts/fmea_catalog.py generate"


def render_module(entries: Sequence[FmeaEntry]) -> str:
    """Детерминированный текст модуля `FmeaId`: члены в порядке каталога."""
    lines = [
        "# Generated by scripts/fmea_catalog.py from harness/fmea/catalog.toml. Do not edit.",
        '"""Постоянные идентификаторы режимов отказа FMEA (ADR 0041)."""',
        "",
        "from enum import StrEnum",
        "",
        "",
        "class FmeaId(StrEnum):",
        '    """Член - режим отказа из каталога; значение - его постоянный GUID."""',
    ]
    if entries:
        lines.append("")
    lines.extend(f'    {member_name(item.title)} = "{item.id}"' for item in entries)
    return "\n".join(lines) + "\n"


def write_module(catalog: Path, module: Path) -> None:
    """Перегенерировать модуль `FmeaId` из каталога."""
    module.write_text(render_module(load_catalog(catalog)), encoding="utf-8", newline="\n")


def check_module(catalog: Path, module: Path) -> bool:
    """Совпадает ли модуль байт-в-байт с тем, что сгенерировал бы каталог."""
    expected = render_module(load_catalog(catalog)).encode("utf-8")
    return module.is_file() and module.read_bytes() == expected


def append_entry(catalog: Path, title: str) -> FmeaEntry:
    """Дописать заготовку записи с новым uuid4; файл меняется только если каталог остаётся валидным."""
    text = catalog.read_text(encoding="utf-8")
    if text and not text.endswith("\n"):
        text += "\n"
    values = {name: "" for name in FIELDS} | {"id": str(uuid.uuid4()), "title": title}
    block = "".join(f'{name} = "{value}"\n' for name, value in values.items())
    combined = f"{text}\n[[failure_mode]]\n{block}"
    entries = parse_catalog(combined, str(catalog))
    catalog.write_text(combined, encoding="utf-8", newline="\n")
    return entries[-1]


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="scripts/fmea_catalog.py", description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("generate", help="regenerate harness/fmea/ids.py")
    generate.add_argument(
        "--check", action="store_true", help="fail when ids.py drifts from the catalog"
    )
    new = commands.add_parser("new", help="append an entry skeleton with a fresh uuid4 id")
    new.add_argument("title", help="slug of the failure mode, for example git-timeout")
    for command in (generate, new):
        command.add_argument("--module", type=Path, default=MODULE_PATH)
    db = commands.add_parser("db", help="build the read-only SQLite file .harness/fmea.db")
    db.add_argument("--db", type=Path, default=DB_PATH)
    for command in (generate, new, db):
        command.add_argument("--catalog", type=Path, default=CATALOG_PATH)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Точка входа CLI: 0 успех, 1 расхождение модуля, 2 ошибка каталога или сборки файла."""
    args = _parser().parse_args(argv)
    catalog: Path = args.catalog
    try:
        if args.command == "db":
            build_db(load_catalog(catalog), args.db)
            return 0
        module: Path = args.module
        if args.command == "new":
            added = append_entry(catalog, args.title)
            write_module(catalog, module)
            print(f"added {added.title} with id {added.id}; fill in its fields in {catalog}")
        elif args.check:
            if check_module(catalog, module):
                return 0
            print(
                f"{module} does not match {catalog}; run `{REGENERATE}` and commit the result",
                file=sys.stderr,
            )
            return 1
        else:
            write_module(catalog, module)
    except (FmeaCatalogError, FmeaDbError) as error:
        return print_and_exit(error)
    return 0


if __name__ == "__main__":
    sys.exit(main())
