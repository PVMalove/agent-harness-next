"""Публикации triage следуют правилу Project-Only Metadata во всех формах трекера."""

from __future__ import annotations

import shlex
from pathlib import Path

import pytest

from scripts.clean_room.support import run_hook

ROOT = Path(__file__).resolve().parents[2]
TRIAGE = ROOT / "skills" / "first-party" / "engineering" / "triage"
SKILL = TRIAGE / "SKILL.md"
SITE_PAGES = (
    ROOT / "site" / "docs" / "skills" / "triage.md",
    ROOT / "site" / "docs" / "skills" / "triage.en.md",
)
HOOK = ROOT / "harness" / "project" / "hooks" / "block-public-attribution.sh"
HOOK_ALLOWS = 0
HOOK_BLOCKS = 2
OLD_DISCLAIMER = "> *This was generated by AI during triage.*"
TRIAGE_NOTES = (
    "## Triage Notes\n\n"
    "**What we've established so far:**\n\n"
    "- The bug reproduces on the integration branch.\n"
)
TRACKER_FORMS = (
    "gh issue comment 42 --body-file {path}",
    "gh pr comment 42 --body-file {path}",
    "GITLAB_HOST=gitlab.example.invalid glab api projects/7/issues/42/notes -F body=@{path}",
    "GITLAB_HOST=gitlab.example.invalid glab api projects/7/merge_requests/42/notes -F body=@{path}",
)


def _text(path: Path) -> str:
    return " ".join(path.read_text(encoding="utf-8").split())


@pytest.mark.parametrize(
    "source", [*sorted(TRIAGE.rglob("*.md")), *SITE_PAGES], ids=lambda p: p.name
)
def test_triage_does_not_require_a_generated_by_marker(source: Path) -> None:
    assert "generated by ai" not in _text(source).lower()


@pytest.mark.parametrize("source", [SKILL, *SITE_PAGES], ids=lambda p: p.name)
def test_triage_publication_follows_project_only_metadata(source: Path) -> None:
    assert "Project-Only Metadata" in _text(source)


@pytest.mark.parametrize("form", TRACKER_FORMS)
@pytest.mark.parametrize(
    ("body", "expected"),
    [
        pytest.param(TRIAGE_NOTES, HOOK_ALLOWS, id="triage-notes"),
        pytest.param(
            f"{OLD_DISCLAIMER}\n\n{TRIAGE_NOTES}", HOOK_BLOCKS, id="old-disclaimer"
        ),
    ],
)
def test_triage_tracker_forms_follow_the_attribution_policy(
    tmp_path: Path, form: str, body: str, expected: int
) -> None:
    path = tmp_path / "issue-comment-42-triage.md"
    path.write_text(body, encoding="utf-8")

    result = run_hook(HOOK, tmp_path, form.format(path=shlex.quote(str(path))))

    assert result.returncode == expected, result.stderr
