"""scripts/fmea_catalog.py: FmeaId generation, drift check and entry creation (ADR 0041)."""

from __future__ import annotations

import importlib.util
import uuid
import types
from pathlib import Path

import pytest

from harness.fmea.catalog import CATALOG_PATH, load_catalog
from scripts import fmea_catalog

GUID_A = "0b6f2a4e-3c1d-4e8a-9f2b-7d5c1a2b3c4d"
GUID_B = "5a1e9c3b-7f2d-4b6a-8c0e-1d2f3a4b5c6d"
REAL_MODULE = CATALOG_PATH.with_name("ids.py")


def entry(guid: str, title: str) -> str:
    return (
        f'[[failure_mode]]\nid = "{guid}"\ntitle = "{title}"\nmode = ""\ndetection = ""\n'
        'recovery = ""\ntest = ""\nresidual_risk = ""\n'
    )


@pytest.fixture
def paths(tmp_path: Path) -> tuple[Path, Path]:
    catalog = tmp_path / "catalog.toml"
    catalog.write_text("# header\n" + entry(GUID_A, "git-timeout"), encoding="utf-8")
    return catalog, tmp_path / "ids.py"


def run(paths: tuple[Path, Path], *args: str) -> int:
    catalog, module = paths
    return fmea_catalog.main([*args, "--catalog", str(catalog), "--module", str(module)])


def import_module(path: Path) -> types.ModuleType:
    spec = importlib.util.spec_from_file_location(f"fmea_ids_{abs(hash(path))}", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_generate_writes_an_importable_fmea_id(paths: tuple[Path, Path]) -> None:
    assert run(paths, "generate") == 0

    fmea_id = import_module(paths[1]).FmeaId
    assert fmea_id.GIT_TIMEOUT == GUID_A
    assert [member.name for member in fmea_id] == ["GIT_TIMEOUT"]


def test_generated_text_is_deterministic(paths: tuple[Path, Path]) -> None:
    run(paths, "generate")
    first = paths[1].read_bytes()
    run(paths, "generate")
    assert paths[1].read_bytes() == first
    assert first.startswith(b"# Generated by scripts/fmea_catalog.py")
    assert b"\r\n" not in first


def test_empty_catalog_gives_an_empty_valid_enum(paths: tuple[Path, Path]) -> None:
    paths[0].write_text("# only comments\n", encoding="utf-8")

    assert run(paths, "generate") == 0
    assert list(import_module(paths[1]).FmeaId) == []


def test_check_passes_after_generate(paths: tuple[Path, Path]) -> None:
    run(paths, "generate")
    assert run(paths, "generate", "--check") == 0


def test_check_fails_when_the_catalog_changes(
    paths: tuple[Path, Path], capsys: pytest.CaptureFixture[str]
) -> None:
    run(paths, "generate")
    with paths[0].open("a", encoding="utf-8") as handle:
        handle.write(entry(GUID_B, "lock-busy"))

    assert run(paths, "generate", "--check") == 1
    assert "python scripts/fmea_catalog.py generate" in capsys.readouterr().err


def test_check_fails_when_the_module_is_edited(paths: tuple[Path, Path]) -> None:
    run(paths, "generate")
    paths[1].write_text(paths[1].read_text(encoding="utf-8") + "# edit\n", encoding="utf-8")

    assert run(paths, "generate", "--check") == 1


def test_check_fails_when_the_module_is_missing(paths: tuple[Path, Path]) -> None:
    assert run(paths, "generate", "--check") == 1
    assert not paths[1].exists()


def test_invalid_catalog_reports_an_error(
    paths: tuple[Path, Path], capsys: pytest.CaptureFixture[str]
) -> None:
    paths[0].write_text(entry("bad", "git-timeout"), encoding="utf-8")

    assert run(paths, "generate") == 2
    assert "REMEDY:" in capsys.readouterr().err
    assert not paths[1].exists()


def test_committed_module_matches_the_shipped_catalog() -> None:
    assert fmea_catalog.main(["generate", "--check"]) == 0
    assert REAL_MODULE.read_text(encoding="utf-8") == fmea_catalog.render_module(load_catalog())


def test_new_appends_a_uuid4_skeleton_and_regenerates(paths: tuple[Path, Path]) -> None:
    run(paths, "generate")
    before = paths[0].read_text(encoding="utf-8")

    assert run(paths, "new", "lock-busy") == 0

    entries = load_catalog(paths[0])
    assert paths[0].read_text(encoding="utf-8").startswith(before)
    assert [item.title for item in entries] == ["git-timeout", "lock-busy"]
    added = entries[1]
    assert uuid.UUID(added.id).version == 4
    assert (added.mode, added.detection, added.recovery, added.test, added.residual_risk) == (
        "",
        "",
        "",
        "",
        "",
    )
    assert run(paths, "generate", "--check") == 0
    assert import_module(paths[1]).FmeaId.LOCK_BUSY == added.id


def test_new_on_a_file_without_trailing_newline(paths: tuple[Path, Path]) -> None:
    paths[0].write_text("# header", encoding="utf-8")

    assert run(paths, "new", "git-timeout") == 0
    assert [item.title for item in load_catalog(paths[0])] == ["git-timeout"]


def test_new_ids_differ(paths: tuple[Path, Path]) -> None:
    run(paths, "new", "a")
    run(paths, "new", "b")
    assert len({item.id for item in load_catalog(paths[0])}) == 3


@pytest.mark.parametrize("title", ["git-timeout", "git_timeout", "Bad Title"])
def test_rejected_new_leaves_files_unchanged(paths: tuple[Path, Path], title: str) -> None:
    run(paths, "generate")
    catalog_before = paths[0].read_bytes()
    module_before = paths[1].read_bytes()

    assert run(paths, "new", title) == 2
    assert paths[0].read_bytes() == catalog_before
    assert paths[1].read_bytes() == module_before


def test_new_accepts_no_id(paths: tuple[Path, Path]) -> None:
    with pytest.raises(SystemExit) as info:
        run(paths, "new", "lock-busy", "--id", GUID_B)
    assert info.value.code == 2
    assert GUID_B not in paths[0].read_text(encoding="utf-8")
