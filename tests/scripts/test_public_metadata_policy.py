"""CI and publication hooks distinguish project vocabulary from attribution."""

from __future__ import annotations

import shlex
import subprocess
import sys
from pathlib import Path

import pytest

from scripts import check_public_metadata
from scripts.clean_room.support import run_hook

HOOK = (
    Path(__file__).resolve().parents[2]
    / "harness/project/hooks/block-public-attribution.sh"
)


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("fix: repair Claude Code worker", 0),
        ("docs: describe Codex unavailable", 0),
        ("fix: update OpenAI adapter", 0),
        ("docs: describe ChatGPT integration", 0),
        ("fix: support GPT-4o and GPT_5", 0),
        ("docs: describe Copilot integration", 0),
        ("fix: update Gemini adapter", 0),
        ("docs: describe AI agent and AI-assistant roles", 0),
        ("fix: handle .claude/settings.json and CLAUDE.md", 0),
        ("Release notes generated by the build script", 0),
        ("Co-Authored-By: PVMalove <dev@example.invalid>", 0),
        ("Co-Authored-By: Alice Smith <alice@example.invalid>", 0),
        ("Co-Authored-By: Claude Dupont <claude@example.invalid>", 0),
        ("Co-Authored-By: Codex <bot@example.invalid>", 1),
        ("_Co-Authored-By: Claude Code <bot@example.invalid>_", 1),
        ("Generated by Codex", 1),
        ("Written by Claude Code", 1),
        ("Created with OpenAI", 1),
        ("Authored using ChatGPT", 1),
        ("Produced via Copilot", 1),
        ("Generated by Gemini", 1),
        ("Written by GPT-4o", 1),
        ("_Generated by [Claude Code](https://claude.ai/code)_", 1),
        ("AI-generated summary", 1),
        ("https://claude.ai/code/session/example", 1),
        ("https://chatgpt.com/c/example", 1),
        ("https://chat.openai.com/c/example", 1),
    ],
)
def test_public_text_allows_runtime_names_and_human_coauthors(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    text: str,
    expected: int,
) -> None:
    body = tmp_path / "message.md"
    body.write_text(text, encoding="utf-8")
    monkeypatch.setattr(
        sys, "argv", ["check_public_metadata.py", "--pr-body-file", str(body)]
    )

    assert check_public_metadata.main() == expected
    for command in (
        f"git commit -F {shlex.quote(str(body))}",
        f"gh pr create --body-file {shlex.quote(str(body))}",
        f"glab mr create --title {shlex.quote(text)}",
        f"gh issue comment 1 --body-file {shlex.quote(str(body))}",
    ):
        result = run_hook(HOOK, tmp_path, command)
        assert result.returncode == expected * 2, result.stderr


@pytest.mark.parametrize(
    ("message", "expected"),
    [
        ("fix: support Claude, Codex, OpenAI, ChatGPT, GPT-5, Copilot and Gemini", 0),
        ("fix: parser\n\nCo-Authored-By: Alice <alice@example.invalid>", 0),
        ("chore: generated by Codex", 1),
        ("fix: parser\n\nCo-Authored-By: Codex <bot@example.invalid>", 1),
    ],
)
def test_commit_and_push_checks_use_the_same_attribution_policy(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    message: str,
    expected: int,
) -> None:
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    subprocess.run(
        [
            "git",
            "-C",
            str(tmp_path),
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.invalid",
            "commit",
            "--allow-empty",
            "-qm",
            message,
        ],
        check=True,
    )
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(
        sys, "argv", ["check_public_metadata.py", "--commit-range", "HEAD"]
    )

    assert check_public_metadata.main() == expected
    result = run_hook(HOOK, tmp_path, "git push origin HEAD")
    assert result.returncode == expected * 2, result.stderr


def test_in_github_actions_a_violation_is_an_error_annotation(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    body = tmp_path / "body.md"
    body.write_text("Generated by Codex\n", encoding="utf-8")
    monkeypatch.setenv("GITHUB_ACTIONS", "true")
    monkeypatch.setattr(sys, "argv", ["check", "--pr-body-file", str(body)])

    assert check_public_metadata.main() == 1

    out = capsys.readouterr().out
    assert out.startswith(
        "::error title=Public Git metadata::PR body: forbidden metadata near "
    )
